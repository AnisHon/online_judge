-- 补齐教师、管理员、超级管理员的后台路由菜单关联。
-- 菜单（M/I）决定动态路由是否生成；按钮权限仍由各自的 perms 独立控制。
use db_user;

-- 教师需要教师功能根菜单，否则已有的 30/31/32 子菜单无法组成树。
insert ignore into sys_role_menu(role_id, menu_id)
values (2, 3), (2, 30), (2, 31), (2, 32);

-- 管理员的后台路由集合：题目、用户和系统管理，不授予教师业务菜单。
delete from sys_role_menu where role_id = 3 and menu_id = 3;
insert ignore into sys_role_menu(role_id, menu_id)
