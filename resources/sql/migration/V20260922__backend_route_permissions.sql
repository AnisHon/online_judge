    (3, 1), (3, 10), (3, 11), (3, 12), (3, 13), (3, 14),
    (3, 2), (3, 20), (3, 21), (3, 22), (3, 23),
    (3, 4), (3, 41), (3, 42), (3, 43), (3, 44), (3, 45);

-- 超级管理员保留全部后台路由；显式补齐可让老数据库安全重复执行迁移。
